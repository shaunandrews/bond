import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const design = readFileSync(resolve(root, 'DESIGN.md'), 'utf8')
const behavior = readFileSync(resolve(root, 'design-system.behavior.yml'), 'utf8')

function scalarSection(source, name) {
  const match = source.match(new RegExp(`^${name}:\\n((?:  [^\\n]+\\n?)+)`, 'm'))
  if (!match) throw new Error(`Missing ${name} section`)
  return Object.fromEntries([...match[1].matchAll(/^  ([\w-]+):\s+"([^"]+)"$/gm)].map(([, key, value]) => [key, value]))
}

function nestedSection(source, name) {
  const match = source.match(new RegExp(`^${name}:\\n([\\s\\S]*?)(?=^[a-z-]+:|(?![\\s\\S]))`, 'm'))
  if (!match) throw new Error(`Missing ${name} section`)
  const output = {}
  for (const [, group, body] of match[1].matchAll(/^  ([\w-]+):\n((?:    [^\n]+\n?)+)/gm)) {
    output[group] = Object.fromEntries([...body.matchAll(/^    ([\w-]+):\s+"([^"]+)"$/gm)].map(([, key, value]) => [key, value]))
  }
  return output
}

const frontmatter = design.match(/^---\n([\s\S]*?)\n---/)
if (!frontmatter) throw new Error('DESIGN.md requires YAML frontmatter')
const colors = scalarSection(frontmatter[1], 'colors')
const typography = scalarSection(frontmatter[1], 'typography')
const rounded = scalarSection(frontmatter[1], 'rounded')
const spacing = scalarSection(frontmatter[1], 'spacing')
const themes = nestedSection(behavior, 'themes')
const layers = scalarSection(behavior, 'layers')
const motion = scalarSection(behavior, 'motion')

const manifest = { colors, typography, rounded, spacing, themes, layers, motion }
const header = '/* Generated by scripts/generate-design-system.mjs. Do not edit. */'
const cssVars = (values, prefix) => Object.entries(values).map(([key, value]) => `  --${prefix}-${key}: ${value};`).join('\n')
const css = `${header}\n\n@theme reference {\n${cssVars(colors, 'color')}\n}\n\n:root {\n${cssVars(colors, 'color')}\n${cssVars(typography, 'font')}\n${cssVars(rounded, 'radius')}\n${cssVars(spacing, 'space')}\n${cssVars(layers, 'z')}\n${cssVars(motion, 'duration')}\n  --ease-out: ${motion['ease-out']};\n${cssVars(themes.light, 'color')}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root {\n${cssVars(themes.dark, 'color')}\n  }\n}\n`
const ts = `// Generated by scripts/generate-design-system.mjs. Do not edit.\nexport const designTokens = ${JSON.stringify(manifest, null, 2)} as const\nexport type DesignTokenGroup = keyof typeof designTokens\n`

function emit(path, content) {
  if (process.argv.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      throw new Error(`${path.replace(root + '/', '')} is stale; run npm run design-system:generate`)
    }
    return
  }
  writeFileSync(path, content)
}

emit(resolve(root, 'src/renderer/design-system.generated.css'), css)
emit(resolve(root, 'src/renderer/design-system.generated.ts'), ts)
